package magc

import (
	"testing"
)

func TestBite(t *testing.T) {
	b := Init()

	____ := -1
	b.AddMust("noop")
	b.AddMust("____", 0xfa, 0xd8, 0xff, 0xe0, 0x00, 0xee, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01)
	b.AddMust("subset", 0x89)
	b.AddMust("subset2", 0x89, 0x50)
	b.AddMust("subset3", ____, 0x50)
	b.AddMust("superset", 0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a)
	b.AddMust("wild-ez1", 0x90, ____, 0x91)
	b.AddMust("wild-ez2", 0x52, 0x49, 0x46, 0x46, ____, ____, ____, ____, 0x41, 0x56, 0x49, 0x20)
	b.AddMust("wild-beg", ____, 0x00, 0xff, 0x30)
	b.AddMust("nomatch", 0xff, 0xd8, 0xff, 0xe0, 0x00, 0xee, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01)

	table := b.Get()

	tests := []struct {
		name  string
		input []byte
		res   string
	}{
		{"no match empty", []byte{}, ""},
		{"no match", []byte{0xf1, 0xf2, 0x12, 0x23, 0xea}, ""},
		{"exact match", []byte{0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a}, "superset"},
		{"subset match", []byte{0x89, 0x49, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a}, "subset"},
		{"easy wildcard match 1", []byte{0x90, 0xea, 0x91, 0x11, 0x00, 0xff}, "wild-ez1"},
		{"easy wildcard match 2", []byte{0x52, 0x49, 0x46, 0x46, 0x11, 0xaf, 0xff, 0x00, 0x41, 0x56, 0x49, 0x20}, "wild-ez2"},
		{"easy wildcard match 3", []byte{0x52, 0x49, 0x46, 0x46, 0x14, 0xe1, 0xc8, 0x00, 0x41, 0x56, 0x49, 0x20, 0x12}, "wild-ez2"},
		{"easy beginning wildcard match", []byte{0x33, 0x00, 0xff, 0x30}, "wild-beg"},
		{"easy beginning wildcard no match", []byte{0x32, 0x00, 0xff, 0x31}, ""},
		{"ambiguous wildcard match", []byte{0x89, 0x50, 0x46, 0x46, 0x14, 0xe1, 0xc8, 0x00, 0x41, 0x56, 0x49, 0x20, 0x12}, "subset2"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			res, ok := table.Find(tt.input)
			if ok == true {
				if res.(string) != tt.res {
					t.Errorf(`%s: failed. Expected "%s", got "%s"`, tt.name, tt.res, res)
				}
			} else {
				if tt.res != "" {
					t.Errorf(`%s: failed. Expected "%s", got nothing`, tt.name, tt.res)
				}
			}

		})
	}
}
